import { createClient, SupabaseClient } from '@supabase/supabase-js';

export interface SupabaseConfig {
  url: string;
  anonKey: string;
  connected?: boolean;
  lastTested?: string;
}

const STORAGE_KEY = 'raba_supabase_config_v1';

// Read config from env vars or localStorage
export function getStoredSupabaseConfig(): SupabaseConfig {
  const envUrl = (import.meta.env.VITE_SUPABASE_URL as string) || '';
  const envKey = (import.meta.env.VITE_SUPABASE_ANON_KEY as string) || '';

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      return {
        url: parsed.url || envUrl,
        anonKey: parsed.anonKey || envKey,
        connected: parsed.connected,
        lastTested: parsed.lastTested
      };
    }
  } catch (e) {
    console.warn('Could not read Supabase config from localStorage:', e);
  }

  return {
    url: envUrl,
    anonKey: envKey,
    connected: Boolean(envUrl && envKey)
  };
}

export function saveStoredSupabaseConfig(config: SupabaseConfig): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
    // Reset client cache
    cachedClient = null;
  } catch (e) {
    console.warn('Could not save Supabase config to localStorage:', e);
  }
}

let cachedClient: SupabaseClient | null = null;

export function getSupabaseClient(): SupabaseClient | null {
  if (cachedClient) return cachedClient;

  const config = getStoredSupabaseConfig();
  if (!config.url || !config.anonKey) {
    return null;
  }

  try {
    cachedClient = createClient(config.url, config.anonKey, {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
      },
    });
    return cachedClient;
  } catch (err) {
    console.error('Failed to create Supabase client:', err);
    return null;
  }
}

/**
 * Test connectivity to the configured Supabase instance
 */
export async function testSupabaseConnection(url?: string, anonKey?: string): Promise<{
  success: boolean;
  message: string;
  details?: any;
}> {
  const targetUrl = url || getStoredSupabaseConfig().url;
  const targetKey = anonKey || getStoredSupabaseConfig().anonKey;

  if (!targetUrl || !targetKey) {
    return {
      success: false,
      message: 'يرجى إدخال كل من Project URL و Public Anon Key لـ Supabase',
    };
  }

  try {
    const client = createClient(targetUrl, targetKey);
    // Ping Supabase using a light call (get auth session or query information)
    const { error } = await client.auth.getSession();
    
    if (error) {
      return {
        success: false,
        message: `خطأ في الاتصال: ${error.message}`,
        details: error,
      };
    }

    // Update stored status
    const current = getStoredSupabaseConfig();
    saveStoredSupabaseConfig({
      ...current,
      url: targetUrl,
      anonKey: targetKey,
      connected: true,
      lastTested: new Date().toISOString(),
    });

    return {
      success: true,
      message: '✓ تم الاتصال بـ Supabase بنجاح واكتمال الربط المباشر!',
    };
  } catch (err: any) {
    return {
      success: false,
      message: `فشل الاتصال: ${err?.message || 'خطأ غير معروف'}`,
      details: err,
    };
  }
}

