  const slug = (post?.slug || '').toLowerCase();
  const category = (post?.category || '').toLowerCase();

  let targetSlug = 'aba-therapy';
  if (slug.includes('occupational-therapy') || category === 'occupational') {
    targetSlug = 'occupational-therapy';
  } else if (slug.includes('echolalia') || category === 'speech') {
    targetSlug = 'speech-therapy';
  } else if (
    slug.includes('mall-crying') ||
    slug.includes('pairing-procedure') ||
    category === 'aba'
  ) {
    targetSlug = 'aba-therapy';
  } else if (
    slug.includes('depersonalization') ||
    slug.includes('schema-therapy') ||
    slug.includes('bobo-doll') ||
    category === 'psychology'
  ) {
    targetSlug = 'psychological-therapy';
  } else if (category === 'sensory') {
    targetSlug = 'sensory-integration';
  } else if (category === 'learning') {
    targetSlug = 'learning-difficulties';
  }

  const matched = getServiceSeoBySlug(targetSlug) || SERVICE_SEO_ROUTES[0];
  return {
    slug: matched.slug,
    title: matched.h1,
    titleEn: matched.h1En,
    description: matched.description,
  };
